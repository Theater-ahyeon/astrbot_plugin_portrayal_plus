# 匹配规则：`/名称` 后面**不能紧接 ASCII 字母数字**（排除 /usr/bin、/reset123），
# 其余情况（句子中间、后接中文、标点、结束）都视为表情。
_NAME_PATTERN = "|".join(
    re.escape(name) for name in sorted(NAME_TO_EMOJI, key=len, reverse=True)
)
_SLASH_EMOJI_RE = re.compile(rf"/({_NAME_PATTERN})(?![A-Za-z0-9_])")


def face_segment_to_emoji(seg_type: str, data: dict) -> str:
    """把 OneBot 的 face / mface 段转成 emoji

    Returns:
        对应的 emoji；**无法确定时返回空串**（宁可不加，也不要塞错表情）。
    """
    if not isinstance(data, dict):
        return ""

    # mface（收藏/表情包）只认名字，id 体系不统一
    if seg_type == "mface":
        for key in ("name", "summary"):
            raw = str(data.get(key) or "").strip()
            if raw in NAME_TO_EMOJI:
                return NAME_TO_EMOJI[raw]
        return ""

    raw = str(data.get("id") or "").strip()
    if raw.lstrip("-").isdigit():
        return FACE_ID_TO_EMOJI.get(int(raw), "")
    # 有些实现直接给名字
    return NAME_TO_EMOJI.get(raw, "")


# 明确的命令白名单：即使名字撞上表情名也不转换（当前无冲突，留作双保险）
_COMMAND_NAMES = frozenset({"reset", "new", "help", "menu", "persona", "clear"})


def slash_emoji_to_emoji(text: str) -> str:
    """把 `/擦汗`、`/偷笑` 这类 QQ 表情文本转成真 emoji

    只替换**确认为表情名**的写法；`/reset`、`/new` 等真命令原样保留
    （后接 ASCII 字母数字的斜杠串一律不动，例如 `/usr/bin`、`/new123`）。
    """
    if not text or "/" not in text:
        return text

    def repl(m: re.Match) -> str:
        name = m.group(1)
        if name.lower() in _COMMAND_NAMES:
            return m.group(0)
        return NAME_TO_EMOJI[name]

    return _SLASH_EMOJI_RE.sub(repl, text)


def normalize_bot_emoji(text: str) -> str:
    """统一处理文本里的表情：CQ 码 -> emoji，斜杠表情 -> emoji"""
    if not text:
        return text
    if "[CQ:face" in text:
        text = re.sub(
            r"\[CQ:face,id=(-?\d+)\]",
            lambda m: FACE_ID_TO_EMOJI.get(int(m.group(1)), ""),
            text,
        )
    return slash_emoji_to_emoji(text)
